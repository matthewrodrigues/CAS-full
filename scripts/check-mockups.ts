// npm run design:check: checks every mockup in design/ and writes the review gallery.
// For each page: head links, raw colors, axe, 44px tap targets, 20px question text, reduced
// motion. Screenshots go to design/review/shots/ and the gallery to design/index.html.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { chromium } from '@playwright/test'
import { checkPage, startDesignServer } from './mockup-browser'
import { checkHead, mockupFiles, scanDesignColors, viewportFor } from './mockup-rules'

const root = join(process.cwd(), 'design')
const shotsDir = join(root, 'review', 'shots')
mkdirSync(shotsDir, { recursive: true })

const shotName = (file: string) => file.replace(/\.html$/, '').replaceAll('/', '__') + '.png'
const escape = (text: string) => text.replace(/[&<>"]/g, (c) => `&${{ '&': 'amp', '<': 'lt', '>': 'gt', '"': 'quot' }[c]};`)

const files = mockupFiles(root)
const problems: string[] = scanDesignColors(root).map((v) => `${v.file}:${v.line}: raw color ${v.match}`)
for (const file of files) for (const p of checkHead(readFileSync(join(root, file), 'utf8'))) problems.push(`${file}: ${p}`)

const server = await startDesignServer(root)
const browser = await chromium.launch()
try {
  for (const file of files) {
    const context = await browser.newContext()
    const page = await context.newPage()
    for (const p of await checkPage(page, server.url, file)) problems.push(`${file}: ${p}`)
    await page.screenshot({ path: join(shotsDir, shotName(file)), fullPage: true })
    await context.close()
  }
} finally {
  await browser.close()
  await server.close()
}

const cards = files.map((file) => {
  const { width } = viewportFor(file)
  return `<li><a href="${escape(file)}"><img src="review/shots/${escape(shotName(file))}" alt="" width="${width === 390 ? 195 : 480}" loading="lazy"><span>${escape(file)}</span></a></li>`
})
writeFileSync(
  join(root, 'index.html'),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Design gallery</title>
<link rel="stylesheet" href="system/tokens.css">
<style>
  body { font-family: var(--font-sans, system-ui); background: var(--color-bg); color: var(--color-ink); margin: 0; padding: 24px 16px; }
  ul { list-style: none; padding: 0; display: flex; flex-wrap: wrap; gap: 24px; }
  a { display: flex; flex-direction: column; gap: 8px; color: inherit; text-decoration: none; }
  img { border-radius: 12px; box-shadow: 0 0 0 1px var(--color-border); }
</style>
</head>
<body>
<h1>Design gallery</h1>
<p>Generated by <code>npm run design:check</code>. ${files.length ? `${files.length} mockups.` : 'No mockups yet.'}</p>
<ul>${cards.join('\n')}</ul>
</body>
</html>
`,
)

if (problems.length) {
  console.error(problems.join('\n'))
  console.error(`\n${problems.length} problem(s) in ${files.length} mockup(s).`)
  process.exit(1)
}
console.log(`design:check passed: ${files.length} mockup(s). Gallery: design/index.html`)
